	public const SAMPLE = 'photo';

	/**
	 * Every service, in the services page's order.
	 *
	 * @return array<string, array<string, mixed>>
	 */
	public static function all(): array {
		return array(
			'photo'     => self::photo(),
			'religious' => self::religious(),
			'content'   => self::content(),
			'event'     => self::event(),
		);
	}

	/**
	 * One service, the sample one for an unknown key.
	 *
	 * @param string $key Service key.
	 */
	public static function get( string $key ): array {
		$all = self::all();

		return $all[ $key ] ?? $all[ self::SAMPLE ];
	}

